import { Duration } from 'aws-cdk-lib';
import { PropertyFilter } from '../core/filters';
import { compact, renderSource, renderWindow } from '../private/experiments';
import { validateRange } from '../private/helpers';
import type { IAction } from '../product-analytics/action';

/**
 * How a metric source aggregates its events.
 */
export enum MetricMath {
  /** Count of events (PostHog's default). */
  TOTAL = 'total',
  /** Sum of a numeric property (set `mathProperty`). */
  SUM = 'sum',
  /** Average of a numeric property (set `mathProperty`). */
  AVG = 'avg',
  /** Minimum of a numeric property (set `mathProperty`). */
  MIN = 'min',
  /** Maximum of a numeric property (set `mathProperty`). */
  MAX = 'max',
  /** Count of unique sessions. */
  UNIQUE_SESSION = 'unique_session',
  /** Count of unique users per day. */
  DAU = 'dau',
  /** Count of unique groups (set `mathGroupTypeIndex`). */
  UNIQUE_GROUP = 'unique_group',
  /** A HogQL aggregation expression (set `mathHogql`). */
  HOGQL = 'hogql',
}

/**
 * Whether higher or lower metric values mean success.
 */
export enum MetricGoal {
  /** Higher is better. */
  INCREASE = 'increase',
  /** Lower is better. */
  DECREASE = 'decrease',
}

/**
 * How the steps of a funnel metric must occur.
 */
export enum FunnelOrder {
  /** Steps must happen in the given order (PostHog's default). */
  ORDERED = 'ordered',
  /** Steps may happen in any order. */
  UNORDERED = 'unordered',
}

/**
 * One step of a funnel metric: an event or an action, optionally narrowed by
 * property filters. Set exactly one of `event` and `action`.
 */
export interface FunnelStep {
  /**
   * Event name, e.g. `$pageview` or `purchase_completed`.
   * @default - use `action`
   */
  readonly event?: string;

  /**
   * Action to match instead of a single event.
   * @default - use `event`
   */
  readonly action?: IAction;

  /**
   * Event property filters narrowing which events count.
   * @default - none
   */
  readonly properties?: PropertyFilter[];
}

/**
 * The events a mean metric, or one side of a ratio metric, aggregates. Set
 * exactly one of `event` and `action`.
 */
export interface MetricSource extends FunnelStep {
  /**
   * How to aggregate the events.
   * @default MetricMath.TOTAL
   */
  readonly math?: MetricMath;

  /**
   * Numeric event property to aggregate, e.g. `revenue`. Required for
   * `SUM`, `AVG`, `MIN` and `MAX`.
   * @default - none
   */
  readonly mathProperty?: string;

  /**
   * HogQL aggregation expression. Required for `MetricMath.HOGQL`.
   * @default - none
   */
  readonly mathHogql?: string;

  /**
   * Group type index (0-4) to count. Required for `MetricMath.UNIQUE_GROUP`.
   * @default - none
   */
  readonly mathGroupTypeIndex?: number;
}

/**
 * Options shared by every metric type.
 */
export interface ExperimentMetricBaseOptions {
  /**
   * Human-readable metric name.
   * @default - PostHog shows the event or action name
   */
  readonly name?: string;

  /**
   * Whether higher or lower values mean success.
   * @default MetricGoal.INCREASE
   */
  readonly goal?: MetricGoal;

  /**
   * Stable metric UUID. PostHog generates one when it is left out; set it to
   * keep the metric's identity (and its cached results) stable across
   * updates.
   * @default - generated by PostHog
   */
  readonly uuid?: string;

  /**
   * Only count events within this window after a user's first exposure.
   * Rendered in the largest whole unit (days, hours, minutes or seconds).
   * @default - count events until the experiment ends
   */
  readonly conversionWindow?: Duration;
}

/**
 * Options for `ExperimentMetric.mean()`.
 */
export interface MeanMetricOptions extends ExperimentMetricBaseOptions, MetricSource {
  /**
   * Winsorization lower bound, as a fraction in [0, 1] (e.g. 0.01 for the
   * 1st percentile). Per-user values below it are clamped.
   * @default - no lower clamp
   */
  readonly lowerBoundPercentile?: number;

  /**
   * Winsorization upper bound, as a fraction in [0, 1] (e.g. 0.99 for the
   * 99th percentile). Per-user values above it are clamped.
   * @default - no upper clamp
   */
  readonly upperBoundPercentile?: number;
}

/**
 * Options for `ExperimentMetric.funnel()`.
 */
export interface FunnelMetricOptions extends ExperimentMetricBaseOptions {
  /**
   * Funnel steps after exposure. At least one.
   */
  readonly steps: FunnelStep[];

  /**
   * How the steps must occur.
   * @default FunnelOrder.ORDERED
   */
  readonly orderType?: FunnelOrder;
}

/**
 * Options for `ExperimentMetric.ratio()`.
 */
export interface RatioMetricOptions extends ExperimentMetricBaseOptions {
  /** The numerator, e.g. revenue (`SUM` of `revenue` on `purchase`). */
  readonly numerator: MetricSource;

  /** The denominator, e.g. the number of `purchase` events. */
  readonly denominator: MetricSource;
}

/**
 * An experiment metric, rendered to PostHog's `ExperimentMetric` JSON. Use it
 * for `Experiment.metrics` / `secondaryMetrics` and `SavedMetric.query`.
 */
export class ExperimentMetric {
  /**
   * A mean metric: the per-user count or aggregate of an event or action.
   */
  public static mean(options: MeanMetricOptions): ExperimentMetric {
    validateRange('Mean metric lowerBoundPercentile', options.lowerBoundPercentile, 0, 1);
    validateRange('Mean metric upperBoundPercentile', options.upperBoundPercentile, 0, 1);
    if (options.lowerBoundPercentile !== undefined && options.upperBoundPercentile !== undefined
      && options.lowerBoundPercentile >= options.upperBoundPercentile) {
      throw new Error('Mean metric: lowerBoundPercentile must be less than upperBoundPercentile');
    }
    return new ExperimentMetric(compact({
      ...ExperimentMetric.base('mean', options),
      source: renderSource('Mean metric source', options),
      lower_bound_percentile: options.lowerBoundPercentile,
      upper_bound_percentile: options.upperBoundPercentile,
    }));
  }

  /**
   * A funnel metric: the share of exposed users who complete every step.
   */
  public static funnel(options: FunnelMetricOptions): ExperimentMetric {
    if (options.steps.length === 0) {
      throw new Error('Funnel metric: at least one step is required');
    }
    return new ExperimentMetric(compact({
      ...ExperimentMetric.base('funnel', options),
      series: options.steps.map((s, i) => renderSource(`Funnel metric step ${i + 1}`, s)),
      funnel_order_type: options.orderType,
    }));
  }

  /**
   * A ratio metric: one aggregate divided by another, e.g. revenue per order.
   */
  public static ratio(options: RatioMetricOptions): ExperimentMetric {
    return new ExperimentMetric(compact({
      ...ExperimentMetric.base('ratio', options),
      numerator: renderSource('Ratio metric numerator', options.numerator),
      denominator: renderSource('Ratio metric denominator', options.denominator),
    }));
  }

  /**
   * A metric from raw `ExperimentMetric` JSON, for metric types or options
   * the typed builders don't cover (quantile, retention, breakdowns, ...).
   * `kind` defaults to `ExperimentMetric`; `metric_type` is required.
   */
  public static fromJson(raw: { [key: string]: any }): ExperimentMetric {
    const kind = raw.kind ?? 'ExperimentMetric';
    if (kind !== 'ExperimentMetric') {
      throw new Error(`ExperimentMetric.fromJson: kind must be 'ExperimentMetric', got '${kind}' (legacy query kinds are rejected by PostHog)`);
    }
    if (raw.metric_type === undefined) {
      throw new Error('ExperimentMetric.fromJson: metric_type is required');
    }
    return new ExperimentMetric({ ...raw, kind });
  }

  private static base(metricType: string, options: ExperimentMetricBaseOptions): Record<string, unknown> {
    return {
      kind: 'ExperimentMetric',
      metric_type: metricType,
      uuid: options.uuid,
      name: options.name,
      goal: options.goal,
      ...renderWindow(`${metricType} metric conversionWindow`, options.conversionWindow),
    };
  }

  private constructor(private readonly json: { [key: string]: any }) {}

  /**
   * The metric as PostHog's `ExperimentMetric` JSON object. May contain CDK
   * tokens (e.g. action IDs), which resolve when the template is rendered.
   */
  public render(): { [key: string]: any } {
    return this.json;
  }
}
