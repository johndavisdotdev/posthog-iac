#!/usr/bin/env bash
# Scaffold a new PostHog::<Service>::<Resource> CloudFormation resource type.
#
#   scripts/new-resource.sh PostHog::Organizations::Organization
#
# Creates ./posthog-<service>-<resource>/ with `cfn init` (Go plugin), wires its
# go.mod to the shared internal/posthogcfn module, replaces the example schema
# with a skeleton that already contains the shared TypeConfiguration, removes
# the example docs/inputs, and adds the module to go.work.
set -euo pipefail

TYPE_NAME="${1:?usage: $0 PostHog::<Service>::<Resource>}"
if [[ ! "$TYPE_NAME" =~ ^PostHog::[A-Za-z0-9]+::[A-Za-z0-9]+$ ]]; then
  echo "type name must look like PostHog::Service::Resource" >&2
  exit 1
fi

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CFN="${CFN:-$ROOT/.venv/bin/cfn}"
DIR_NAME="$(echo "$TYPE_NAME" | tr '[:upper:]' '[:lower:]' | sed 's/::/-/g')"
DIR="$ROOT/$DIR_NAME"
MODULE_ROOT="github.com/johndavisdev/posthog-iac"
IMPORT_PATH="$MODULE_ROOT/$DIR_NAME"
SCHEMA="$DIR/$DIR_NAME.json"

if [[ -e "$DIR" ]]; then
  echo "$DIR already exists" >&2
  exit 1
fi

mkdir -p "$DIR"
cd "$DIR"
"$CFN" init -a RESOURCE -t "$TYPE_NAME" go --import-path "$IMPORT_PATH" >/dev/null

# Drop the example "TPS report" content generated by cfn init.
rm -rf docs example_inputs rpdk.log
rmdir internal 2>/dev/null || true
mkdir -p example_inputs examples

# Skeleton schema. Replace properties/identifiers/permissions for the resource.
python3 - "$SCHEMA" "$TYPE_NAME" <<'PY'
import json, sys
path, type_name = sys.argv[1], sys.argv[2]
schema = {
    "typeName": type_name,
    "description": "TODO: describe " + type_name,
    "sourceUrl": "https://github.com/johndavisdev/posthog-iac",
    "documentationUrl": "https://posthog.com/docs/api",
    "definitions": {},
    "typeConfiguration": {
        "properties": {
            "ApiKey": {
                "description": "PostHog personal API key (phx_...) with the scopes this resource type needs. Pass it with a dynamic reference such as {{resolve:ssm-secure:/posthog/api-key}} when calling SetTypeConfiguration; never put it in plain text.",
                "type": "string",
                "minLength": 1
            },
            "BaseUrl": {
                "description": "PostHog API host. Leave unset for PostHog Cloud US (https://us.posthog.com); use https://eu.posthog.com for PostHog Cloud EU, or your instance URL when self-hosting.",
                "type": "string"
            }
        },
        "additionalProperties": False,
        "required": ["ApiKey"]
    },
    "properties": {
        "Id": {"description": "The PostHog ID of the resource.", "type": "string"}
    },
    "additionalProperties": False,
    "required": [],
    "readOnlyProperties": ["/properties/Id"],
    "primaryIdentifier": ["/properties/Id"],
    "tagging": {"taggable": False},
    "handlers": {
        "create": {"permissions": []},
        "read": {"permissions": []},
        "update": {"permissions": []},
        "delete": {"permissions": []},
        "list": {"permissions": []}
    }
}
with open(path, "w") as f:
    json.dump(schema, f, indent=4)
    f.write("\n")
PY

# go.mod: depend on the shared module through a local replace so the project
# builds both inside the go.work workspace and on its own (as `cfn submit` does).
cat > go.mod <<EOF
module $IMPORT_PATH

go 1.26

require $MODULE_ROOT/internal/posthogcfn v0.0.0

replace $MODULE_ROOT/internal/posthogcfn => ../internal/posthogcfn
EOF

# Resolve deps first (cfn generate runs `go fmt`, which needs a tidy go.mod),
# then regenerate model.go / config.go from the skeleton schema.
(cd "$ROOT" && go work use "./$DIR_NAME")
go mod tidy >/dev/null
"$CFN" generate >/dev/null
go mod tidy >/dev/null
rm -f rpdk.log
cat >> .gitignore <<'EOF'

# generated by `cfn submit --dry-run`
*.zip
.hypothesis/
EOF

echo "Created $DIR"
